# usage: DOMAIN=example.com DOCKER_HOST_IP=... python3 gen.py > config/dynamic/routes.yml
# Traefik watches config/dynamic and reloads by itself.
#
# One table decides who gets authentik in front of an app. The same routes serve the LAN and, through
# Pangolin, the internet, so outside behaves exactly like inside.
#   "open"     = the app handles its own login (OIDC, native accounts, sync clients)
#   "auth"     = authentik forward-auth in front of everything
#   "auth-api" = forward-auth, except /api (apps whose mobile clients authenticate with an API key)
#
# Public version: hostnames and ports below are examples, the real table lives in the private repo.
import os

DOMAIN = os.environ.get("DOMAIN", "example.com")
HOST = os.environ.get("DOCKER_HOST_IP", "docker-host")
AUTHENTIK_PORT = int(os.environ.get("AUTHENTIK_PORT", "9000"))

APPS = [
    # (subdomain, host port, mode)
    ("auth", AUTHENTIK_PORT, "open"),
    ("immich", 2283, "open"),
    ("nextcloud", 8080, "open"),
    ("sonarr", 8989, "auth-api"),
    ("dockpeek", 3420, "auth"),
]

d = DOMAIN.replace(".", r"\.")
o = ["# Generated by gen.py - edit the APPS table and regenerate", "http:", "  middlewares:",
     "    authentik:", "      forwardAuth:", f"        address: http://{HOST}:{AUTHENTIK_PORT}/outpost.goauthentik.io/auth/traefik",
     "        trustForwardHeader: true", "        maxResponseBodySize: 1048576", "        authResponseHeaders:"]
o += [f"          - {h}" for h in ["X-authentik-username", "X-authentik-groups", "X-authentik-email", "X-authentik-name", "X-authentik-uid"]]
o += ["  routers:",
      "    authentik-outpost:", f"      rule: HostRegexp(`^.+\\.{d}$`) && PathPrefix(`/outpost.goauthentik.io/`)",
      "      entryPoints: [websecure]", "      service: auth", "      priority: 1000"]
for h, p, m in APPS:
    o += [f"    {h}:", f"      rule: Host(`{h}.{DOMAIN}`)", "      entryPoints: [websecure]", f"      service: {h}"]
    if m.startswith("auth"):
        o.append("      middlewares: [authentik]")
    if m == "auth-api":
        o += [f"    {h}-api:", f"      rule: Host(`{h}.{DOMAIN}`) && PathPrefix(`/api`)", "      entryPoints: [websecure]",
              f"      service: {h}", "      priority: 500"]
o.append("  services:")
for h, p, m in APPS:
    o += [f"    {h}:", "      loadBalancer:", "        passHostHeader: true", "        servers:", f"          - url: http://{HOST}:{p}"]
print("\n".join(o))
